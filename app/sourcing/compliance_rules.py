def detect_category(category: str | None, name: str | None = "") -> str:
    """제품 카테고리/이름으로 규제 영역 판정. 해당 없으면 '일반'."""
    hay = f"{category or ''} {name or ''}"
    for area, keywords in REGULATED_CATEGORIES.items():
        if any(k in hay for k in keywords):
            return area
    return "일반"


def risk_guide(area: str) -> str:
    return RISK_GUIDE.get(area, "특별한 광고 규제 대상이 아님. 과장·허위 표현만 일반적으로 주의.")
